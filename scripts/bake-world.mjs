// Downloads the timeline's world-event pictures once, so the app can ship them instead of fetching at runtime.
// Same rules as js/world.js: Wikipedia lead image per event, kept only if Commons says public domain / CC0.
// Run: node scripts/bake-world.mjs   -> writes img/world/* and js/world-data.js
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { rmSync } from 'node:fs';
import vm from 'node:vm';

const root = new URL('..', import.meta.url).pathname;
const win = { localStorage: { getItem() { return null; }, setItem() {} } };
vm.runInNewContext(readFileSync(root + 'js/world.js', 'utf8'), { window: win, document: {}, fetch: () => { throw new Error('no network'); }, console });
const EVENTS = win.World.EVENTS;
const OVERRIDE = new Map(EVENTS.filter(e => e.img).map(e => [e.wiki, e.img]));
const FREE = /public domain|^pd|cc0|no restrictions/i;
const UA = { 'User-Agent': 'RootlightBake/1.0 (static site build script)' };
const strip = h => (h || '').replace(/<[^>]*>/g, '').replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/&#0?39;/g, "'").replace(/\s+/g, ' ').trim();
const api = async (host, params) => {
  const r = await fetch(`https://${host}/w/api.php?` + new URLSearchParams({ action: 'query', format: 'json', ...params }), { headers: UA });
  if (!r.ok) throw new Error(host + ' ' + r.status);
  return r.json();
};
const slug = s => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const sleep = ms => new Promise(r => setTimeout(r, ms));

async function batch(titles) {
  const a = await api('en.wikipedia.org', { redirects: 1, prop: 'pageimages|extracts', piprop: 'name', exintro: 1, explaintext: 1, exsentences: 2, exlimit: 20, titles: titles.join('|') });
  const alias = new Map();
  for (const n of a.query.normalized || []) alias.set(n.to, n.from);
  for (const r of a.query.redirects || []) alias.set(r.to, alias.get(r.from) || r.from);
  const out = {}, byFile = new Map();
  for (const p of Object.values(a.query.pages)) {
    const asked = alias.get(p.title) || p.title;
    out[asked] = { extract: p.extract || '', page: `https://en.wikipedia.org/wiki/${encodeURIComponent(p.title.replace(/ /g, '_'))}` };
    const file = OVERRIDE.get(asked) || p.pageimage;
    if (file) byFile.set('File:' + file.replace(/_/g, ' '), asked);
  }
  if (byFile.size) {
    const c = await api('commons.wikimedia.org', { prop: 'imageinfo', iiprop: 'url|extmetadata', iiextmetadatafilter: 'LicenseShortName|Artist', iiurlwidth: 1200, titles: [...byFile.keys()].join('|') });
    const cn = new Map((c.query.normalized || []).map(n => [n.to, n.from]));
    for (const p of Object.values(c.query.pages)) {
      const info = p.imageinfo && p.imageinfo[0];
      const asked = byFile.get(cn.get(p.title) || p.title);
      if (!info || !asked) continue;
      const md = info.extmetadata || {};
      const license = md.LicenseShortName ? strip(md.LicenseShortName.value) : '';
      if (!FREE.test(license)) continue;
      out[asked].src = (info.thumburl || info.url).replace(/\?.*$/, '');
      out[asked].credit = { artist: md.Artist ? strip(md.Artist.value).slice(0, 80) : '', license, page: info.descriptionurl };
    }
  }
  return out;
}

async function download(url, path) {
  for (let i = 0; i < 4; i++) {
    const r = await fetch(url, { headers: UA });
    if (r.ok) { writeFileSync(path, Buffer.from(await r.arrayBuffer())); return true; }
    if (r.status !== 429) return false;
    await sleep(3000 * (i + 1));
  }
  return false;
}

mkdirSync(root + 'img/world', { recursive: true });
const titles = EVENTS.map(e => e.wiki), data = {};
for (let i = 0; i < titles.length; i += 20) Object.assign(data, await batch(titles.slice(i, i + 20)));

const baked = {};
for (const [title, d] of Object.entries(data)) {
  const rec = { extract: d.extract, page: d.page };
  if (d.src) {
    const ext = (d.src.match(/\.(jpe?g|png|webp|gif)$/i) || [, 'jpg'])[1].toLowerCase();
    const name = slug(title), big = `img/world/${name}.jpg`, small = `img/world/${name}.thumb.jpg`, tmp = root + `img/world/${name}.tmp.${ext}`;
    const okBig = await download(d.src, tmp); await sleep(400);
    if (okBig) {
      // macOS sips: flatten everything to a modest JPEG so the whole set stays a few MB
      const make = (out, max, q) => execFileSync('sips', ['-s', 'format', 'jpeg', '-s', 'formatOptions', String(q), '-Z', String(max), tmp, '--out', root + out], { stdio: 'ignore' });
      make(big, 1200, 78); make(small, 120, 80);
      rmSync(tmp);
    }
    const okSmall = okBig;
    if (okBig) { rec.img = big; rec.thumb = okSmall ? small : big; rec.credit = d.credit; }
    else console.warn('no picture for', title);
  }
  baked[title] = rec;
}
writeFileSync(root + 'js/world-data.js', '// Generated by scripts/bake-world.mjs. Do not edit.\nwindow.WORLD_BAKED = ' + JSON.stringify(baked) + ';\n');
const n = Object.values(baked).filter(b => b.img).length;
console.log(`${Object.keys(baked).length} events, ${n} with pictures`);
